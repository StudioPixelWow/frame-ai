// ── GET handler ────────────────────────────────────────────────────────

export async function GET() {
  try {
    const existing = await proposalTemplates.getAllAsync();
    if (existing.length >= 11) {
      return NextResponse.json({ message: 'כבר קיימות תבניות', count: existing.length });
    }

    const now = new Date().toISOString();
    const created: ProposalTemplate[] = [];

    for (const seed of TEMPLATES) {
      const template = await proposalTemplates.createAsync({
        ...seed,
        createdAt: now,
        updatedAt: now,
      } as ProposalTemplate);
      created.push(template);
    }

    return NextResponse.json({
      message: `נוצרו ${created.length} תבניות בהצלחה`,
      count: created.length,
      templates: created.map((t) => ({ id: t.id, code: t.code, name: t.name, category: t.category })),
    });
  } catch (error: any) {
    console.error('[seed-templates] Error:', error);
    return NextResponse.json({ error: error.message || 'שגיאה ביצירת תבניות' }, { status: 500 });
  }
}
