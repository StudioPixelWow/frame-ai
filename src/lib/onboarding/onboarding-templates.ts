/**
 * Generate 36 onboarding task objects ready for DB insert.
 * Due dates are calculated from today + template.dayOffset.
 */
export function generateOnboardingTasks(
  clientId: string,
  clientName: string,
): Omit<Task, 'id' | 'createdAt' | 'updatedAt'>[] {
  const today = new Date();

  return ONBOARDING_TASKS.map((template) => {
    const dueDate = new Date(today);
    dueDate.setDate(dueDate.getDate() + template.dayOffset);

    return {
      title: template.title,
      description: template.description,
      status: 'open' as const,
      priority: template.priority,
      clientId,
      clientName,
      assigneeIds: [],
      dueDate: dueDate.toISOString().split('T')[0], // YYYY-MM-DD
      tags: template.tags,
      files: [],
      notes: '',
    };
  });
}
